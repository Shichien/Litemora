for (const [version, aliases] of versions) {
  const data = minecraftData(version)
  const protocol = data.protocol
  const states = {}
  for (const state of ['login', 'configuration', 'play']) {
    if (!protocol[state])
      continue
    const types = protocol[state].toClient.types
    const packet = types.packet[1]
    const names = Object.fromEntries(Object.entries(packet[0].type[1].mappings).map(([id, name]) => [Number(id), name]))
    const dispatch = packet[1].type[1].fields
    states[state] = {
      names,
      packets: Object.fromEntries(Object.entries(dispatch).filter(([name]) => relevant.has(name))),
      types: Object.fromEntries(Object.entries(types).filter(([name]) => name !== 'packet' && (!name.startsWith('packet_') || Object.entries(dispatch).some(([packetName, type]) => relevant.has(packetName) && type === name)))),
    }
  }
  const output = {
    generatedFrom: 'minecraft-data 3.105.0 (MIT; https://github.com/PrismarineJS/minecraft-data)',
    version,
    aliases,
    protocol: data.version.version,
    types: protocol.types,
    states,
    nonWorld,
    blocks: data.blocksArray.map(b => [b.minStateId, b.maxStateId, b.name, b.states.map(s => [s.name, s.values || (s.type === 'bool' ? ['true', 'false'] : Array.from({ length: s.num_values }, (_, i) => String(i)))]), b.transparent, b.boundingBox, b.id]),
    entities: data.entitiesArray.map(e => [e.id, e.name, e.metadataKeys || []]),
    items: data.itemsArray.map(i => [i.id, i.name]),
  }
  fs.writeFileSync(new URL(`./protocol-${data.version.version}.js`, import.meta.url), `// Generated by generate-tables.mjs; minecraft-data is MIT licensed.\nexport default ${JSON.stringify(output)}\n`)
  process.stdout.write(`${version}: protocol ${data.version.version}, ${JSON.stringify(output).length} bytes\n`)
}
